// Generates the reference pages in apps/docs/content/docs/reference/ from the code.
// Usage: pnpm docs:reference [--check]
// Output is deterministic (sorted, no timestamps) so CI can regenerate and diff.
import { execSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { z } from "zod";
import * as toolModules from "@/lib/mcp/tools";
import { allTools } from "@/lib/mcp/tools";
import { APP_ROLES, SCOPED_ROLES } from "@/lib/authz/roles";
import { PARTNER_ROUTES } from "@/lib/partner-routes";

const OUT = "apps/docs/content/docs/reference";
const check = process.argv.includes("--check");

type JsonSchema = {
  type?: string | string[];
  format?: string;
  enum?: unknown[];
  const?: unknown;
  items?: JsonSchema;
  anyOf?: JsonSchema[];
  properties?: Record<string, JsonSchema>;
  required?: string[];
  default?: unknown;
  description?: string;
};

const cell = (s: string) =>
  s.replace(/\s+/g, " ").replace(/\|/g, "\\|").replace(/[{}]/g, (c) => `\\${c}`).replace(/</g, "&lt;").replace(/>/g, "&gt;");
const code = (s: string) => `\`${s.replace(/\|/g, "\\|")}\``;
const byString = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);

function page(title: string, description: string, body: string[]): string {
  return [
    "---",
    `title: ${JSON.stringify(title)}`,
    `description: ${JSON.stringify(description)}`,
    "---",
    "",
    "{/* Generated by scripts/docs/generate-reference.ts. Do not edit: change the code and run `pnpm docs:reference`. */}",
    "",
    ...body,
    "",
  ].join("\n");
}

function typeOf(s: JsonSchema): string {
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.anyOf) return s.anyOf.map(typeOf).join(" | ");
  if (s.type === "array") return `${s.items ? typeOf(s.items) : "unknown"}[]`;
  const t = Array.isArray(s.type) ? s.type.join(" | ") : s.type ?? "unknown";
  return s.format ? `${t} (${s.format})` : t;
}

function fieldsTable(schema: z.ZodType): string[] {
  const json = z.toJSONSchema(schema, { io: "input", unrepresentable: "any" }) as JsonSchema;
  const props = Object.entries(json.properties ?? {}).sort(([a], [b]) => byString(a, b));
  if (props.length === 0) return ["No input fields."];
  const required = new Set(json.required ?? []);
  return [
    "| Field | Type | Required | Default | Description |",
    "| --- | --- | --- | --- | --- |",
    ...props.map(([name, s]) =>
      `| ${code(name)} | ${code(typeOf(s))} | ${required.has(name) ? "yes" : "no"} | ${
        s.default !== undefined ? code(JSON.stringify(s.default)) : ""
      } | ${cell(s.description ?? "")} |`,
    ),
  ];
}

// ── MCP tools ───────────────────────────────────────────────────────────
function mcpPage(): string {
  const index = readFileSync("lib/mcp/tools/index.ts", "utf8");
  const modules = Array.from(index.matchAll(/^export \{ (\w+) \} from "\.\/([\w-]+)";$/gm)).map(([, exportName, file]) => {
    const words = file.replace(/^crm-/, "").split("-").join(" ");
    const tools = (toolModules as unknown as Record<string, typeof allTools>)[exportName];
    return { title: words[0].toUpperCase() + words.slice(1), file: `lib/mcp/tools/${file}.ts`, tools };
  });
  modules.sort((a, b) => byString(a.title, b.title));
  const listed = modules.reduce((n, m) => n + m.tools.length, 0);
  if (listed !== allTools.length) throw new Error(`index.ts exports ${listed} tools, allTools has ${allTools.length}`);

  const body = [
    `The MCP server registers **${allTools.length} tools** in ${modules.length} modules, every entry of \`allTools\` in \`lib/mcp/tools/index.ts\`. Fields come from each tool's zod schema. How to connect, authenticate and add a tool: [MCP server](/docs/developers/mcp).`,
    "",
    "| Module | File | Tools |",
    "| --- | --- | --- |",
    ...modules.map((m) => `| [${m.title}](#${m.title.toLowerCase().replace(/ /g, "-")}) | ${code(m.file)} | ${m.tools.length} |`),
  ];
  for (const m of modules) {
    body.push("", `## ${m.title}`);
    for (const tool of [...m.tools].sort((a, b) => byString(a.name, b.name))) {
      body.push("", `### ${code(tool.name)}`, "", cell(tool.description), "", ...fieldsTable(tool.schema));
    }
  }
  return page("MCP tools", "Every tool the MCP server registers, with its input fields.", body);
}

// ── Roles ───────────────────────────────────────────────────────────────
function rolesPage(): string {
  const entryPoints = execSync("git ls-files -- '*.ts' '*.tsx'", { encoding: "utf8" })
    .split("\n")
    .filter((f) => f && !f.includes("__tests__") && !f.startsWith("tests/"))
    .filter((f) => !["lib/auth-server.ts", "lib/authz/session.ts"].includes(f))
    .filter((f) => /\bpartner:[ ]true\b/.test(readFileSync(f, "utf8")))
    .sort(byString);
  const body = [
    "The access facts that live in code. What the roles mean and how the checks work: [Auth and permissions](/docs/developers/auth-permissions).",
    "",
    "## Roles",
    "",
    "From `APP_ROLES` in `lib/authz/roles.ts`. Roles outside `SCOPED_ROLES` get no rows from the scope helpers unless they have their own branch (`partner`: `lib/authz/scopes/partner.ts`).",
    "",
    "| Role | In `SCOPED_ROLES` |",
    "| --- | --- |",
    ...APP_ROLES.map((r) => `| ${code(r)} | ${SCOPED_ROLES.has(r) ? "yes" : "no"} |`),
    "",
    "## Partner routes",
    "",
    "`PARTNER_ROUTES` in `lib/partner-routes.ts`, enforced by `proxy.ts`. A partner may open these paths and everything below them (`*` is one path segment), plus the dashboard. Every other page redirects to the dashboard and every other API route answers 403.",
    "",
    ...[...PARTNER_ROUTES].sort(byString).map((r) => `- ${code(r)}`),
    "",
    "## Partner entry points",
    "",
    "Files that call `getSession()` or `requireAuthenticated()` with the `partner` option set to `true`. Everywhere else a partner is refused. `__tests__/authz/partner-entry-points.test.ts` fails when this set changes without review.",
    "",
    ...entryPoints.map((f) => `- ${code(f)}`),
  ];
  return page("Roles and access", "Roles, the partner route allow-list and the partner entry points, read from the code.", body);
}

// ── Environment variables ───────────────────────────────────────────────
function envPage(): string {
  const example = new Map<string, string>();
  const lines = readFileSync(".env.example", "utf8").split("\n");
  lines.forEach((line, i) => {
    const m = line.match(/^([A-Z][A-Z0-9_]*)=(?:"[^"]*"|[^#\s]*)\s*(?:#\s*(.*))?$/);
    if (!m) return;
    let purpose = m[2]?.trim() ?? "";
    if (!purpose) {
      // The comment block above this line or above its group of variables.
      let j = i - 1;
      while (j >= 0 && /^[A-Z][A-Z0-9_]*=/.test(lines[j])) j--;
      const block: string[] = [];
      for (; j >= 0 && lines[j].startsWith("#"); j--) block.unshift(lines[j].replace(/^#\s?/, ""));
      purpose = block.join(" ").trim();
    }
    example.set(m[1], purpose);
  });

  const readIn = new Map<string, Set<string>>();
  const files = execSync("git ls-files -- '*.ts' '*.tsx' '*.js' '*.mjs' '*.cjs'", { encoding: "utf8" })
    .split("\n")
    .filter((f) => f && !/^(apps|docs|scripts|tests|e2e|__mocks__)\//.test(f))
    .filter((f) => !/(__tests__\/|\.test\.|\.spec\.|^jest\.|^playwright\.)/.test(f));
  for (const f of files) {
    for (const m of Array.from(readFileSync(f, "utf8").matchAll(/process\.env(?:\.([A-Z][A-Z0-9_]*)|\[["']([A-Z][A-Z0-9_]*)["']\])/g))) {
      const name = m[1] ?? m[2];
      if (!readIn.has(name)) readIn.set(name, new Set());
      readIn.get(name)!.add(f);
    }
  }

  const names = Array.from(new Set(Array.from(example.keys()).concat(Array.from(readIn.keys())))).sort(byString);
  const body = [
    "Every variable listed in `.env.example` or read as `process.env.NAME` in the app code (tests, scripts and the docs app excluded). **Required** is \"yes\" when the `.env.example` comment says so and empty when it says nothing; **Purpose** is that comment. Variables read under a computed name are not listed. What each variable does and when you need it: [Configuration reference](/docs/admins/configuration).",
    "",
    `${names.length} variables.`,
    "",
    "| Variable | Required | In `.env.example` | Purpose | Read in |",
    "| --- | --- | --- | --- | --- |",
    ...names.map((name) => {
      const purpose = example.get(name) ?? "";
      const where = Array.from(readIn.get(name) ?? []).sort(byString);
      const shown = where.slice(0, 3).map(code).join(", ") + (where.length > 3 ? ` +${where.length - 3} more` : "");
      return `| ${code(name)} | ${/\brequired\b/i.test(purpose) ? "yes" : ""} | ${example.has(name) ? "yes" : "no"} | ${cell(purpose)} | ${shown} |`;
    }),
  ];
  return page("Environment variables", "Every environment variable the app reads, from .env.example and the code.", body);
}

// ── Plugins ─────────────────────────────────────────────────────────────
async function pluginsPage(): Promise<string> {
  const ids = readdirSync("plugins", { withFileTypes: true })
    .filter((d) => d.isDirectory() && (existsSync(join("plugins", d.name, "plugin.ts")) || existsSync(join("plugins", d.name, "plugin.tsx"))))
    .map((d) => d.name)
    .sort(byString);
  const body = [
    "The public plugins in `plugins/*`, the same set `scripts/plugins/generate-registry.mjs` puts into the registry. How plugins work: [Plugins](/docs/developers/plugins); installing and configuring them: [Plugins (admin)](/docs/admins/plugins).",
  ];
  for (const id of ids) {
    const p = (await import(`@/plugins/${id}/plugin`)).default;
    body.push(
      "",
      `## ${cell(p.name)}`,
      "",
      cell(p.description ?? ""),
      "",
      "| | |",
      "| --- | --- |",
      `| Id | ${code(p.id)} |`,
      `| Version | ${code(p.version)} |`,
      `| SDK | ${code(p.sdk)} |`,
      `| Permissions | ${[...(p.permissions ?? [])].sort(byString).map(code).join(", ")} |`,
      "",
      "### Settings",
      "",
      ...(p.settings ? fieldsTable(p.settings) : ["No settings."]),
    );
  }
  return page("Plugins", "The bundled plugins with their versions, permissions and settings.", body);
}

async function main() {
  const files: Record<string, string> = {
    "meta.json": `${JSON.stringify({ title: "Reference", icon: "BookOpen", pages: ["index", "mcp-tools", "roles", "environment", "plugins"], root: true }, null, 2)}\n`,
    "index.mdx": page("Reference", "Pages generated from the code: MCP tools, roles, environment variables and plugins.", [
      "These pages are generated from the source code by `pnpm docs:reference`, and CI fails when they fall behind it.",
      "",
      "- [MCP tools](/docs/reference/mcp-tools)",
      "- [Roles and access](/docs/reference/roles)",
      "- [Environment variables](/docs/reference/environment)",
      "- [Plugins](/docs/reference/plugins)",
    ]),
    "mcp-tools.mdx": mcpPage(),
    "roles.mdx": rolesPage(),
    "environment.mdx": envPage(),
    "plugins.mdx": await pluginsPage(),
  };
  if (check) {
    const present = existsSync(OUT) ? readdirSync(OUT) : [];
    const stale = [
      ...Object.keys(files).filter((f) => !existsSync(join(OUT, f)) || readFileSync(join(OUT, f), "utf8") !== files[f]),
      ...present.filter((f) => !(f in files)),
    ].sort(byString);
    if (stale.length) {
      console.error(`Stale reference pages in ${OUT}: ${stale.join(", ")}. Run: pnpm docs:reference`);
      process.exit(1);
    }
    process.exit(0);
  }
  mkdirSync(OUT, { recursive: true });
  for (const [f, content] of Object.entries(files)) writeFileSync(join(OUT, f), content);
  console.log(`Generated ${Object.keys(files).length} files → ${OUT}`);
  process.exit(0);
}

main();
