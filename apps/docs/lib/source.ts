import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { llms, loader } from 'fumadocs-core/source';
import type * as PageTree from 'fumadocs-core/page-tree';
import { lucideIconsPlugin } from 'fumadocs-core/source/lucide-icons';
import { docsContentRoute, docsImageRoute, docsRoute } from './shared';
import { defineDocs } from 'fumadocs-mdx/macro';
import { metaSchema, pageSchema } from 'fumadocs-core/source/schema';

const docs = defineDocs({
  dir: 'content/docs',
  docs: {
    schema: pageSchema,
    postprocess: {
      includeProcessedMarkdown: true,
    },
  },
  meta: {
    schema: metaSchema,
  },
});

// Older versions, generated by scripts/fetch-versions.mjs (gitignored).
const versionDocs = defineDocs({
  dir: 'content/versions',
  docs: { schema: pageSchema },
  meta: { schema: metaSchema },
});

// See https://fumadocs.dev/docs/headless/source-api for more info
export const source = loader({
  baseUrl: docsRoute,
  source: docs.toFumadocsSource(),
  plugins: [lucideIconsPlugin()],
});

export const docsLlms = llms(source, {
  renderPage: async (page) => `# ${page.data.title} (${page.url})

${await page.data.getText('processed')}`,
});

// Pages under /docs/v0.35/... Same base URL as Latest: the first slug is the version.
export const versionSource = loader({
  baseUrl: docsRoute,
  source: versionDocs.toFumadocsSource(),
  plugins: [lucideIconsPlugin()],
});

export type DocsVersion = { slug: string; minor: string; tag: string; kind: 'docs' | 'notes' };

const manifestFile = path.join(process.cwd(), 'content/versions/versions.json');
const manifest: { latest: string; versions: DocsVersion[] } = existsSync(manifestFile)
  ? JSON.parse(readFileSync(manifestFile, 'utf8'))
  : { latest: '', versions: [] };

/** Older versions for the switcher, newest first. */
export const versions = manifest.versions.map(({ slug, minor }) => ({ slug, minor }));

/** Minor of the newest release tag, e.g. "0.36" (empty without fetched versions). */
export const latestMinor = manifest.latest.replace(/^v(\d+\.\d+)\..*$/, '$1');

export function getVersion(slug: string | undefined): DocsVersion | undefined {
  return manifest.versions.find((v) => v.slug === slug);
}

/** A Latest or older-version page by its full slug. */
export function getDocsPage(slug: string[] | undefined) {
  return getVersion(slug?.[0]) ? versionSource.getPage(slug) : source.getPage(slug);
}

/** Sidebar tree of one older version: the contents of its folder. */
export function getVersionTree(slug: string): PageTree.Root {
  const folder = versionSource
    .getPageTree()
    .children.find((node): node is PageTree.Folder => node.type === 'folder' && node.$ref?.folder === slug);
  if (!folder) return { name: slug, children: [] };
  return { name: folder.name, children: folder.index ? [folder.index, ...folder.children] : folder.children };
}

/** Where switching to `to` ("latest" or "v0.35") from `pathname` lands: the same page, else that version's index. */
export function switchVersionUrl(pathname: string, to: string): string {
  const slugs = pathname.split('/').filter(Boolean).slice(1);
  const rest = getVersion(slugs[0]) ? slugs.slice(1) : slugs;
  const target = to === 'latest' ? rest : [to, ...rest];
  return getDocsPage(target)?.url ?? (to === 'latest' ? docsRoute : `${docsRoute}/${to}`);
}
